/**
 * Builds the educational recovery-curve index from the Soma 1.0 seed.
 *
 * Reads:
 *   apps/api/prisma/seed/recovery-curves.ts
 *
 * Writes:
 *   apps/web/src/features/recovery-dashboard/anatomy/recovery-curves.generated.ts
 *
 * The web app imports that file. It does not import Prisma or the API.
 * `pnpm --filter @soma/web build` and `dev` run this script first.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const curvesPath = path.join(root, "apps/api/prisma/seed/recovery-curves.ts");
const outPath = path.join(
  root,
  "apps/web/src/features/recovery-dashboard/anatomy/recovery-curves.generated.ts",
);

function parseRecoveryCurves(source) {
  const start = source.indexOf("export const RECOVERY_CURVES = [");
  const end = source.indexOf("] satisfies");
  if (start < 0 || end < 0) {
    throw new Error("Could not locate RECOVERY_CURVES in the seed file.");
  }
  const body = source
    .slice(start + "export const RECOVERY_CURVES = ".length, end + 1)
    .replace(/as const/g, "");
  const curves = eval(body);
  if (!Array.isArray(curves) || curves.length === 0) {
    throw new Error("Parsed recovery curves are empty.");
  }
  return curves;
}

const curves = parseRecoveryCurves(fs.readFileSync(curvesPath, "utf8"));
const keys = new Set(curves.map((item) => `${item.organId}|${item.substanceId}`));
if (keys.size !== curves.length) {
  throw new Error("Duplicate organ/substance pairs in recovery curves seed.");
}

const file = `/* Generated by apps/web/scripts/build-recovery-catalog.mjs. Do not edit.
 * Source: apps/api/prisma/seed/recovery-curves.ts
 * Refresh with pnpm --filter @soma/web build or pnpm --filter @soma/web dev.
 */
export const recoveryCurves = ${JSON.stringify(curves, null, 2)} as const;
`;

fs.writeFileSync(outPath, file);
console.log(`recovery catalog: ${curves.length} curves`);
