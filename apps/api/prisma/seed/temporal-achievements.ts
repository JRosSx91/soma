export function temporalAchievementId(
  substanceId: TemporalSubstanceId,
  days: TemporalThresholdDays,
): string {
  return `${substanceId}-temporal-${days}`;
}

export const TEMPORAL_ACHIEVEMENTS = TEMPORAL_SUBSTANCES.flatMap((substanceId) =>
  TEMPORAL_THRESHOLDS.map((days) => {
    const id = temporalAchievementId(substanceId, days);
    return {
      id,
      family: "temporal" as const,
      tier: TIER_BY_DAYS[days],
      titleKey: `${id}.title`,
      descriptionKey: `${id}.description`,
      triggerSubstanceId: substanceId,
      triggerAbstinenceDays: days as number,
    };
  }),
);

export function temporalAchievementCreateData(
  row: (typeof TEMPORAL_ACHIEVEMENTS)[number],
) {
  return {
    id: row.id,
    family: row.family,
    tier: row.tier,
    titleKey: row.titleKey,
    descriptionKey: row.descriptionKey,
    triggerSubstanceId: row.triggerSubstanceId,
    triggerAbstinenceDays: row.triggerAbstinenceDays,
    triggerOrganId: null,
    triggerRecoveryThreshold: null,
    hidden: false,
  };
}
